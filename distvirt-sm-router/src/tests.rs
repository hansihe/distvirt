const A1: AlphaId = AlphaId(1);
const A2: AlphaId = AlphaId(2);
const A3: AlphaId = AlphaId(3);
const B1: BetaId = BetaId(1);
const B2: BetaId = BetaId(2);
const G1: GammaId = GammaId(1);
const G2: GammaId = GammaId(2);

#[test]
fn basic_signal_propagation() {
    let mut router = Router::new(16);
    router.create_alpha(A1, AlphaSm::new());
    router.create_beta(B1, BetaSm::new());

    // Create edge A1 -> B1, propagate (B1 gets empty aggregation)
    router.set_alpha_to_beta_edges(A1, vec![B1]);
    router.propagate();

    let b1 = router.beta_instances.get(&B1).unwrap();
    assert_eq!(b1.deliveries.len(), 1);
    assert_eq!(b1.deliveries[0], BetaSmInput::DemandInput(0));

    // Set signal on A1
    router.set_alpha_demand(A1, true);
    router.propagate();

    let b1 = router.beta_instances.get(&B1).unwrap();
    assert_eq!(b1.deliveries.len(), 2);
    assert_eq!(b1.deliveries[1], BetaSmInput::DemandInput(1));
}

#[test]
fn change_detection_no_delivery_on_same_value() {
    let mut router = Router::new(16);
    router.create_alpha(A1, AlphaSm::new());
    router.create_beta(B1, BetaSm::new());

    router.set_alpha_to_beta_edges(A1, vec![B1]);
    router.set_alpha_demand(A1, true);
    router.propagate();

    let b1 = router.beta_instances.get(&B1).unwrap();
    assert_eq!(b1.deliveries.len(), 1);

    // Set same value again — no propagation
    router.set_alpha_demand(A1, true);
    router.propagate();

    let b1 = router.beta_instances.get(&B1).unwrap();
    assert_eq!(b1.deliveries.len(), 1); // still 1, no new delivery
}

#[test]
fn multi_edge_aggregation() {
    let mut router = Router::new(16);
    router.create_alpha(A1, AlphaSm::new());
    router.create_alpha(A2, AlphaSm::new());
    router.create_alpha(A3, AlphaSm::new());
    router.create_beta(B1, BetaSm::new());

    // Three sources -> one target
    router.set_alpha_to_beta_edges(A1, vec![B1]);
    router.set_alpha_to_beta_edges(A2, vec![B1]);
    router.set_alpha_to_beta_edges(A3, vec![B1]);
    router.propagate();

    // Set signals: A1=true, A2=false, A3=true
    router.set_alpha_demand(A1, true);
    router.set_alpha_demand(A2, false);
    router.set_alpha_demand(A3, true);
    router.propagate();

    // B1 should receive count=2 (A1 and A3 are true)
    let b1 = router.beta_instances.get(&B1).unwrap();
    let last = b1.deliveries.last().unwrap();
    assert_eq!(*last, BetaSmInput::DemandInput(2));
}

#[test]
fn cascading_signal_to_edge_to_signal() {
    let mut router = Router::new(16);
    router.create_alpha(A1, AlphaSm::new());

    // When B1 receives DemandInput, it creates BetaToAlpha edge back to A1
    // and sets Status signal, which cascades to A1's StatusInput.
    let mut b1 = BetaSm::new();
    b1.on_handle = Some(Box::new(|input, ctx| {
        let BetaSmInput::DemandInput(count) = input else {
            return;
        };
        if *count > 0 {
            ctx.set_beta_to_alpha_edges(vec![A1]);
            ctx.set_status(42);
        }
    }));
    router.create_beta(B1, b1);

    // Setup: A1 --AlphaToBeta--> B1
    router.set_alpha_to_beta_edges(A1, vec![B1]);

    router.set_alpha_demand(A1, true);
    router.propagate();

    // B1 received DemandInput(1)
    let b1 = router.beta_instances.get(&B1).unwrap();
    assert!(b1
        .deliveries
        .iter()
        .any(|inp| *inp == BetaSmInput::DemandInput(1)));

    // A1 received StatusInput([42]) via cascade
    let a1 = router.alpha_instances.get(&A1).unwrap();
    assert!(a1
        .deliveries
        .iter()
        .any(|inp| *inp == AlphaSmInput::StatusInput(vec![42])));
}

