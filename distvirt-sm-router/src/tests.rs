    router.create_gamma(G1);
    router.create_gamma(G2);

    // Two gamma ports -> B1
    router.set_gamma_to_beta_edges(G1, vec![B1]);
    router.set_gamma_to_beta_edges(G2, vec![B1]);
    router.set_gamma_value(G1, 10);
