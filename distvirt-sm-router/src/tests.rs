use std::collections::{HashMap, HashSet, VecDeque};

use crate::{Aggregator, ListAggregator, SmHandler};

// ===========================================================================
// Test Topology — hand-written "generated" code
//
// SM types: AlphaSm, BetaSm
// Port types: GammaPort
//
// Signals:
//   AlphaSm::Demand(bool)
//   BetaSm::Status(u32)
//   GammaPort::Value(u32)
//
// Edges:
//   AlphaToBeta: AlphaSm -> BetaSm
//   BetaToAlpha: BetaSm -> AlphaSm
//   GammaToBeta: GammaPort -> BetaSm
//
// Inputs:
//   BetaSm::DemandInput:
//     sources: [(AlphaToBeta, AlphaSm::Demand)]
//     aggregator: CountTrueAggregator -> u32
//
//   BetaSm::ConfigInput:
//     sources: [(GammaToBeta, GammaPort::Value)]
//     aggregator: ListAggregator -> Vec<u32>
//
//   AlphaSm::StatusInput:
//     sources: [(BetaToAlpha, BetaSm::Status)]
//     aggregator: ListAggregator -> Vec<u32>
// ===========================================================================

// ---- ID types ----

#[derive(Copy, Clone, Eq, PartialEq, Hash, Debug)]
struct AlphaId(u64);

#[derive(Copy, Clone, Eq, PartialEq, Hash, Debug)]
struct BetaId(u64);

#[derive(Copy, Clone, Eq, PartialEq, Hash, Debug)]
struct GammaId(u64);

// ---- SM input enums (one per SM type) ----
// MACRO NOTE: Generated by the macro. One variant per aggregated input,
// plus one variant per received event channel.

#[derive(Debug, PartialEq)]
enum AlphaSmInput {
    StatusInput(Vec<u32>),
}

#[derive(Debug, PartialEq)]
enum BetaSmInput {
    DemandInput(u32),
    ConfigInput(Vec<u32>),
}

// ---- SM handler contexts (one per SM type) ----
// MACRO NOTE: Generated by the macro. One Ctx struct per SM type with
// Option fields for each signal and edge set the SM can produce.
// The propagation loop creates a fresh Ctx, passes it to the handler,
// then applies effects via apply_*_effects().

struct AlphaSmCtx {
    #[allow(dead_code)]
    id: AlphaId,
    set_demand: Option<bool>,
    set_alpha_to_beta: Option<Vec<BetaId>>,
}

impl AlphaSmCtx {
    fn new(id: AlphaId) -> Self {
        AlphaSmCtx {
            id,
            set_demand: None,
            set_alpha_to_beta: None,
        }
    }

    #[allow(dead_code)]
    pub fn id(&self) -> AlphaId {
        self.id
    }

    pub fn set_demand(&mut self, value: bool) {
        self.set_demand = Some(value);
    }

    #[allow(dead_code)]
    pub fn set_alpha_to_beta_edges(&mut self, targets: Vec<BetaId>) {
        self.set_alpha_to_beta = Some(targets);
    }
}

struct BetaSmCtx {
    #[allow(dead_code)]
    id: BetaId,
    set_status: Option<u32>,
    set_beta_to_alpha: Option<Vec<AlphaId>>,
}

impl BetaSmCtx {
    fn new(id: BetaId) -> Self {
        BetaSmCtx {
            id,
            set_status: None,
            set_beta_to_alpha: None,
        }
    }

    #[allow(dead_code)]
    pub fn id(&self) -> BetaId {
        self.id
    }

    pub fn set_status(&mut self, value: u32) {
        self.set_status = Some(value);
    }

    pub fn set_beta_to_alpha_edges(&mut self, targets: Vec<AlphaId>) {
        self.set_beta_to_alpha = Some(targets);
    }
}

// ---- SM trait impls ----
// Users implement SmHandler on their SM structs. The Input and Ctx
// associated types are generated per-SM-type by the macro.
// The SM struct holds whatever state the SM needs.

// AlphaSm: test SM that records deliveries for assertions.
struct AlphaSm {
    deliveries: Vec<AlphaSmInput>,
    on_handle: Option<Box<dyn FnMut(&AlphaSmInput, &mut AlphaSmCtx)>>,
}

impl AlphaSm {
    fn new() -> Self {
        AlphaSm {
            deliveries: Vec::new(),
            on_handle: None,
        }
    }
}

impl SmHandler for AlphaSm {
    type Input = AlphaSmInput;
    type Ctx = AlphaSmCtx;

    fn handle(&mut self, input: Self::Input, ctx: &mut Self::Ctx) {
        if let Some(ref mut cb) = self.on_handle {
            cb(&input, ctx);
        }
        self.deliveries.push(input);
    }
}

// BetaSm: test SM that records deliveries for assertions.
struct BetaSm {
    deliveries: Vec<BetaSmInput>,
    on_handle: Option<Box<dyn FnMut(&BetaSmInput, &mut BetaSmCtx)>>,
}

impl BetaSm {
    fn new() -> Self {
        BetaSm {
            deliveries: Vec::new(),
            on_handle: None,
        }
    }
}

impl SmHandler for BetaSm {
    type Input = BetaSmInput;
    type Ctx = BetaSmCtx;

    fn handle(&mut self, input: Self::Input, ctx: &mut Self::Ctx) {
        if let Some(ref mut cb) = self.on_handle {
            cb(&input, ctx);
        }
        self.deliveries.push(input);
    }
}

// ---- Aggregators ----

struct CountTrueAggregator;

impl Aggregator for CountTrueAggregator {
    type Input = (AlphaId, bool);
    type Output = u32;

    fn aggregate(&self, inputs: &[(AlphaId, bool)]) -> u32 {
        inputs.iter().filter(|(_, demand)| *demand).count() as u32
    }
}

type AlphaStatusAggregator = ListAggregator<BetaId, u32>;
type BetaConfigAggregator = ListAggregator<GammaId, u32>;

// ---- Dirty queue ----

#[derive(Clone, Eq, PartialEq, Hash, Debug)]
enum DirtyInput {
    BetaDemand(BetaId),
    BetaConfig(BetaId),
    AlphaStatus(AlphaId),
}

// ---- Router ----
// MACRO NOTE: The macro generates this entire struct. SM types are stored
// as HashMap<Id, SmStruct> — the router owns SM instances directly.
// Port types have no user-defined state, so they remain as HashSets.

struct Router {
    // SM instance storage (owns SM structs)
    alpha_instances: HashMap<AlphaId, AlphaSm>,
    beta_instances: HashMap<BetaId, BetaSm>,

    // Port instance registry (no user state)
    gamma_instances: HashSet<GammaId>,

    // Signals (initialized to Default::default() at instance creation)
    alpha_demand: HashMap<AlphaId, bool>,
    beta_status: HashMap<BetaId, u32>,
    gamma_value: HashMap<GammaId, u32>,

    // Edges: AlphaToBeta (AlphaSm -> BetaSm)
    alpha_to_beta_fwd: HashMap<AlphaId, Vec<BetaId>>,
    alpha_to_beta_rev: HashMap<BetaId, HashSet<AlphaId>>,

    // Edges: BetaToAlpha (BetaSm -> AlphaSm)
    beta_to_alpha_fwd: HashMap<BetaId, Vec<AlphaId>>,
    beta_to_alpha_rev: HashMap<AlphaId, HashSet<BetaId>>,

    // Edges: GammaToBeta (GammaPort -> BetaSm)
    gamma_to_beta_fwd: HashMap<GammaId, Vec<BetaId>>,
    gamma_to_beta_rev: HashMap<BetaId, HashSet<GammaId>>,

    // Last delivered aggregation results (for change detection)
    last_beta_demand: HashMap<BetaId, u32>,
    last_beta_config: HashMap<BetaId, Vec<u32>>,
    last_alpha_status: HashMap<AlphaId, Vec<u32>>,

    // Propagation
    dirty: VecDeque<DirtyInput>,
    depth_limit: usize,
}

impl Router {
    fn new(depth_limit: usize) -> Self {
        Router {
            alpha_instances: HashMap::new(),
            beta_instances: HashMap::new(),
            gamma_instances: HashSet::new(),
            alpha_demand: HashMap::new(),
            beta_status: HashMap::new(),
            gamma_value: HashMap::new(),
            alpha_to_beta_fwd: HashMap::new(),
            alpha_to_beta_rev: HashMap::new(),
            beta_to_alpha_fwd: HashMap::new(),
            beta_to_alpha_rev: HashMap::new(),
            gamma_to_beta_fwd: HashMap::new(),
            gamma_to_beta_rev: HashMap::new(),
            last_beta_demand: HashMap::new(),
            last_beta_config: HashMap::new(),
            last_alpha_status: HashMap::new(),
            dirty: VecDeque::new(),
            depth_limit,
        }
    }

    // ---- Instance creation ----
    // SM creation takes the user's SM struct and stores it in the router.
    // Signals are initialized to Default::default(). No eager delivery occurs
    // (the SM's first delivery happens when edges are established).

    fn create_alpha(&mut self, id: AlphaId, sm: AlphaSm) {
        self.alpha_instances.insert(id, sm);
        self.alpha_demand.insert(id, Default::default());
    }

    fn create_beta(&mut self, id: BetaId, sm: BetaSm) {
        self.beta_instances.insert(id, sm);
        self.beta_status.insert(id, Default::default());
    }

    fn create_gamma(&mut self, id: GammaId) {
        self.gamma_instances.insert(id);
        self.gamma_value.insert(id, Default::default());
    }

    // ---- Instance destruction ----

    /// Destroy an AlphaSm instance. Returns the SM struct if it existed.
    /// - Removes outgoing edges (AlphaToBeta), triggers re-aggregation on targets.
    /// - Leaves incoming edges (BetaToAlpha pointing here) as dangling.
    /// - Removes signal storage and last-delivered results.
    fn destroy_alpha(&mut self, id: AlphaId) -> Option<AlphaSm> {
        let sm = self.alpha_instances.remove(&id);
        self.alpha_demand.remove(&id);
        self.last_alpha_status.remove(&id);
        // Remove outgoing edges
        self.set_alpha_to_beta_edges(id, vec![]);
        sm
    }

    /// Destroy a BetaSm instance. Returns the SM struct if it existed.
    /// - Removes outgoing edges (BetaToAlpha), triggers re-aggregation on targets.
    /// - Leaves incoming edges (AlphaToBeta, GammaToBeta pointing here) as dangling.
    /// - Removes signal storage and last-delivered results.
    fn destroy_beta(&mut self, id: BetaId) -> Option<BetaSm> {
        let sm = self.beta_instances.remove(&id);
        self.beta_status.remove(&id);
        self.last_beta_demand.remove(&id);
        self.last_beta_config.remove(&id);
        // Remove outgoing edges
        self.set_beta_to_alpha_edges(id, vec![]);
        sm
    }

    /// Remove a GammaPort instance.
    /// Ports get full cleanup — all edges from/to the port are removed.
    fn remove_gamma(&mut self, id: GammaId) {
        self.gamma_instances.remove(&id);
        self.gamma_value.remove(&id);
        // Remove outgoing edges (GammaToBeta)
        self.set_gamma_to_beta_edges(id, vec![]);
        // GammaPort has no incoming edge types in this topology,
        // but if it did, we would remove them here too.
    }

    // ---- External signal setters ----
    // These do change detection and enqueue dirty entries, but don't propagate.

    fn set_alpha_demand(&mut self, id: AlphaId, value: bool) {
        if self.alpha_demand.get(&id) == Some(&value) {
            return;
        }
        self.alpha_demand.insert(id, value);
        // AlphaSm::Demand feeds BetaSm::DemandInput through AlphaToBeta
        if let Some(targets) = self.alpha_to_beta_fwd.get(&id) {
            for &beta_id in targets {
                self.dirty.push_back(DirtyInput::BetaDemand(beta_id));
            }
        }
    }

    fn set_beta_status(&mut self, id: BetaId, value: u32) {
        if self.beta_status.get(&id) == Some(&value) {
            return;
        }
        self.beta_status.insert(id, value);
        // BetaSm::Status feeds AlphaSm::StatusInput through BetaToAlpha
        if let Some(targets) = self.beta_to_alpha_fwd.get(&id) {
            for &alpha_id in targets {
                self.dirty.push_back(DirtyInput::AlphaStatus(alpha_id));
            }
        }
    }

    fn set_gamma_value(&mut self, id: GammaId, value: u32) {
        if self.gamma_value.get(&id) == Some(&value) {
            return;
        }
        self.gamma_value.insert(id, value);
        // GammaPort::Value feeds BetaSm::ConfigInput through GammaToBeta
        if let Some(targets) = self.gamma_to_beta_fwd.get(&id) {
            for &beta_id in targets {
                self.dirty.push_back(DirtyInput::BetaConfig(beta_id));
            }
        }
    }

    // ---- External edge setters ----

    fn set_alpha_to_beta_edges(&mut self, source: AlphaId, new_targets: Vec<BetaId>) {
        let old_set: HashSet<BetaId> = self
            .alpha_to_beta_fwd
            .get(&source)
            .map(|v| v.iter().copied().collect())
            .unwrap_or_default();
        let new_set: HashSet<BetaId> = new_targets.iter().copied().collect();

        let removed: Vec<BetaId> = old_set.difference(&new_set).copied().collect();
        let added: Vec<BetaId> = new_set.difference(&old_set).copied().collect();

        // No-op if edge set unchanged
        if removed.is_empty() && added.is_empty() {
            return;
        }

        // Update forward index
        if new_targets.is_empty() {
            self.alpha_to_beta_fwd.remove(&source);
        } else {
            self.alpha_to_beta_fwd.insert(source, new_targets);
        }

        // Update reverse index
        for &tgt in &removed {
            if let Some(sources) = self.alpha_to_beta_rev.get_mut(&tgt) {
                sources.remove(&source);
                if sources.is_empty() {
                    self.alpha_to_beta_rev.remove(&tgt);
                }
            }
        }
        for &tgt in &added {
            self.alpha_to_beta_rev
                .entry(tgt)
                .or_default()
                .insert(source);
        }

        // AlphaToBeta feeds BetaSm::DemandInput — enqueue affected targets
        for tgt in removed.iter().chain(added.iter()) {
            self.dirty.push_back(DirtyInput::BetaDemand(*tgt));
        }
    }

    fn set_beta_to_alpha_edges(&mut self, source: BetaId, new_targets: Vec<AlphaId>) {
        let old_set: HashSet<AlphaId> = self
            .beta_to_alpha_fwd
            .get(&source)
            .map(|v| v.iter().copied().collect())
            .unwrap_or_default();
        let new_set: HashSet<AlphaId> = new_targets.iter().copied().collect();

        let removed: Vec<AlphaId> = old_set.difference(&new_set).copied().collect();
        let added: Vec<AlphaId> = new_set.difference(&old_set).copied().collect();

        // No-op if edge set unchanged
        if removed.is_empty() && added.is_empty() {
            return;
        }

        if new_targets.is_empty() {
            self.beta_to_alpha_fwd.remove(&source);
        } else {
            self.beta_to_alpha_fwd.insert(source, new_targets);
        }

        for &tgt in &removed {
            if let Some(sources) = self.beta_to_alpha_rev.get_mut(&tgt) {
                sources.remove(&source);
                if sources.is_empty() {
                    self.beta_to_alpha_rev.remove(&tgt);
                }
            }
        }
        for &tgt in &added {
            self.beta_to_alpha_rev
                .entry(tgt)
                .or_default()
                .insert(source);
        }

        // BetaToAlpha feeds AlphaSm::StatusInput — enqueue affected targets
        for tgt in removed.iter().chain(added.iter()) {
            self.dirty.push_back(DirtyInput::AlphaStatus(*tgt));
        }
    }

    fn set_gamma_to_beta_edges(&mut self, source: GammaId, new_targets: Vec<BetaId>) {
        let old_set: HashSet<BetaId> = self
            .gamma_to_beta_fwd
            .get(&source)
            .map(|v| v.iter().copied().collect())
            .unwrap_or_default();
        let new_set: HashSet<BetaId> = new_targets.iter().copied().collect();

        let removed: Vec<BetaId> = old_set.difference(&new_set).copied().collect();
        let added: Vec<BetaId> = new_set.difference(&old_set).copied().collect();

        if removed.is_empty() && added.is_empty() {
            return;
        }

        if new_targets.is_empty() {
            self.gamma_to_beta_fwd.remove(&source);
        } else {
            self.gamma_to_beta_fwd.insert(source, new_targets);
        }

        for &tgt in &removed {
            if let Some(sources) = self.gamma_to_beta_rev.get_mut(&tgt) {
                sources.remove(&source);
                if sources.is_empty() {
                    self.gamma_to_beta_rev.remove(&tgt);
                }
            }
        }
        for &tgt in &added {
            self.gamma_to_beta_rev
                .entry(tgt)
                .or_default()
                .insert(source);
        }

        // GammaToBeta feeds BetaSm::ConfigInput — enqueue affected targets
        for tgt in removed.iter().chain(added.iter()) {
            self.dirty.push_back(DirtyInput::BetaConfig(*tgt));
        }
    }

    // ---- Aggregation ----

    fn aggregate_beta_demand(&self, beta_id: BetaId) -> u32 {
        let mut inputs = Vec::new();
        if let Some(sources) = self.alpha_to_beta_rev.get(&beta_id) {
            for &alpha_id in sources {
                if let Some(&demand) = self.alpha_demand.get(&alpha_id) {
                    inputs.push((alpha_id, demand));
                }
            }
        }
        CountTrueAggregator.aggregate(&inputs)
    }

    fn aggregate_beta_config(&self, beta_id: BetaId) -> Vec<u32> {
        let mut inputs = Vec::new();
        if let Some(sources) = self.gamma_to_beta_rev.get(&beta_id) {
            for &gamma_id in sources {
                if let Some(&value) = self.gamma_value.get(&gamma_id) {
                    inputs.push((gamma_id, value));
                }
            }
        }
        BetaConfigAggregator::new().aggregate(&inputs)
    }

    fn aggregate_alpha_status(&self, alpha_id: AlphaId) -> Vec<u32> {
        let mut inputs = Vec::new();
        if let Some(sources) = self.beta_to_alpha_rev.get(&alpha_id) {
            for &beta_id in sources {
                if let Some(&status) = self.beta_status.get(&beta_id) {
                    inputs.push((beta_id, status));
                }
            }
        }
        AlphaStatusAggregator::new().aggregate(&inputs)
    }

    // ---- Effects application ----

    fn apply_alpha_effects(&mut self, id: AlphaId, ctx: AlphaSmCtx) {
        if let Some(value) = ctx.set_demand {
            self.set_alpha_demand(id, value);
        }
        if let Some(targets) = ctx.set_alpha_to_beta {
            self.set_alpha_to_beta_edges(id, targets);
        }
    }

    fn apply_beta_effects(&mut self, id: BetaId, ctx: BetaSmCtx) {
        if let Some(value) = ctx.set_status {
            self.set_beta_status(id, value);
        }
        if let Some(targets) = ctx.set_beta_to_alpha {
            self.set_beta_to_alpha_edges(id, targets);
        }
    }

    // ---- Propagation loop ----
    // Dispatches directly to owned SM structs via SmHandler trait.
    // Uses take-call-reinsert pattern to avoid borrow conflicts:
    // the SM is temporarily removed from the HashMap during handler
    // invocation so we can mutate both the SM and the router.

    fn propagate(&mut self) {
        let mut depth = 0;

        while !self.dirty.is_empty() {
            depth += 1;
            if depth == self.depth_limit {
                panic!(
                    "Signal router depth limit ({}) exceeded",
                    self.depth_limit
                );
            }
            if depth == self.depth_limit - 1 {
                eprintln!(
                    "WARNING: Signal router approaching depth limit ({}/{})",
                    depth, self.depth_limit
                );
            }

            // Drain current wave, dedup
            let wave: Vec<DirtyInput> = self.dirty.drain(..).collect();
            let mut seen = HashSet::new();

            for entry in wave {
                if !seen.insert(entry.clone()) {
                    continue;
                }

                match entry {
                    DirtyInput::BetaDemand(beta_id) => {
                        if !self.beta_instances.contains_key(&beta_id) {
                            continue;
                        }
                        let result = self.aggregate_beta_demand(beta_id);
                        // Skip delivery if aggregated result unchanged
                        if self.last_beta_demand.get(&beta_id) == Some(&result) {
                            continue;
                        }
                        self.last_beta_demand.insert(beta_id, result.clone());

                        // Take SM out, call handler, reinsert
                        let mut sm = self.beta_instances.remove(&beta_id).unwrap();
                        let mut ctx = BetaSmCtx::new(beta_id);
                        sm.handle(BetaSmInput::DemandInput(result), &mut ctx);
                        self.beta_instances.insert(beta_id, sm);

                        self.apply_beta_effects(beta_id, ctx);
                    }
                    DirtyInput::BetaConfig(beta_id) => {
                        if !self.beta_instances.contains_key(&beta_id) {
                            continue;
                        }
                        let result = self.aggregate_beta_config(beta_id);
                        if self.last_beta_config.get(&beta_id) == Some(&result) {
                            continue;
                        }
                        self.last_beta_config.insert(beta_id, result.clone());

                        let mut sm = self.beta_instances.remove(&beta_id).unwrap();
                        let mut ctx = BetaSmCtx::new(beta_id);
                        sm.handle(BetaSmInput::ConfigInput(result), &mut ctx);
                        self.beta_instances.insert(beta_id, sm);

                        self.apply_beta_effects(beta_id, ctx);
                    }
                    DirtyInput::AlphaStatus(alpha_id) => {
                        if !self.alpha_instances.contains_key(&alpha_id) {
                            continue;
                        }
                        let result = self.aggregate_alpha_status(alpha_id);
                        if self.last_alpha_status.get(&alpha_id) == Some(&result) {
                            continue;
                        }
                        self.last_alpha_status.insert(alpha_id, result.clone());

                        let mut sm = self.alpha_instances.remove(&alpha_id).unwrap();
                        let mut ctx = AlphaSmCtx::new(alpha_id);
                        sm.handle(AlphaSmInput::StatusInput(result), &mut ctx);
                        self.alpha_instances.insert(alpha_id, sm);

                        self.apply_alpha_effects(alpha_id, ctx);
                    }
                }
            }
        }
    }
}

