    router.remove_gamma(G2);
    router.propagate();

    let b1 = router.beta_instances.get(&B1).unwrap();
    assert!(b1
        .deliveries
        .iter()
        .any(|inp| *inp == BetaSmInput::ConfigInput(vec![])));
